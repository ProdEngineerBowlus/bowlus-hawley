-- Explicit prototype only. Not in db/migrations; production startup cannot apply it.
create schema if not exists planning_v2;
create table if not exists planning_v2.task_definitions (
  task_id text primary key,
  source_base_id text not null,
  source_record_id text not null,
  unique (source_base_id, source_record_id)
);
create table if not exists planning_v2.task_versions (
  task_id text not null references planning_v2.task_definitions,
  version_hash text not null,
  task_name text not null,
  definition jsonb not null,
  captured_at timestamptz not null,
  primary key (task_id, version_hash)
);
create table if not exists planning_v2.template_catalog (
  task_id text primary key references planning_v2.task_definitions,
  version_hash text not null,
  foreign key (task_id, version_hash) references planning_v2.task_versions
);
create table if not exists planning_v2.route_sources (
  project_id text not null,
  snapshot_hash text not null,
  captured_at timestamptz not null,
  primary key (project_id, snapshot_hash)
);
create table if not exists planning_v2.route_nodes (
  project_id text not null,
  snapshot_hash text not null,
  source_task_id text not null,
  parent_source_task_id text,
  task_id text references planning_v2.task_definitions,
  name text not null,
  section_id text,
  section_name text,
  approximate_phase_day integer check (approximate_phase_day > 0),
  node_kind text not null check (node_kind in ('day_group','work_group','work_item','unmapped')),
  source_position integer not null,
  source_json jsonb not null,
  primary key (project_id, snapshot_hash, source_task_id),
  foreign key (project_id, snapshot_hash) references planning_v2.route_sources,
  foreign key (project_id, snapshot_hash, parent_source_task_id)
    references planning_v2.route_nodes(project_id, snapshot_hash, source_task_id)
    deferrable initially deferred
);
-- Reference schedule rows are preserved, not regenerated from task rows.
create table if not exists planning_v2.schedule_sources (
  source_base_id text not null,
  source_table_id text not null,
  source_record_id text not null,
  source_table_name text not null,
  fields_json jsonb not null,
  primary key (source_base_id, source_table_id, source_record_id)
);
-- Cycle is deliberately not part of work identity. No occurrence is generated by import.
create table if not exists planning_v2.work_occurrences (
  occurrence_id text primary key,
  task_id text not null,
  version_hash text not null,
  subject_kind text not null check (subject_kind in ('vin','batch')),
  subject_id text not null,
  occurrence_number integer not null default 1 check (occurrence_number > 0),
  planned_quantity numeric not null check (planned_quantity > 0),
  original_plan jsonb not null default '{}',
  current_cycle_id text,
  released_estimate_seconds numeric check (released_estimate_seconds >= 0),
  status text not null default 'released' check (status in ('released','in_progress','blocked','completed','accepted','cancelled')),
  unique (task_id, subject_kind, subject_id, occurrence_number),
  foreign key (task_id, version_hash) references planning_v2.task_versions
);
create or replace view planning_v2.task_catalog_review as
select d.task_id, d.source_record_id, v.task_name, v.version_hash, v.definition
from planning_v2.task_definitions d
join planning_v2.template_catalog c using(task_id)
join planning_v2.task_versions v using(task_id,version_hash);
create or replace view planning_v2.dayblocks_review as
select r.project_id,r.snapshot_hash,r.source_task_id,r.parent_source_task_id,
 r.section_name,r.approximate_phase_day,r.node_kind,r.name,r.task_id,
 v.task_name as template_name,r.source_position,r.source_json
from planning_v2.route_nodes r
left join planning_v2.task_catalog_review v using(task_id);
